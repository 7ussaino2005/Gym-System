 /**
     * Name: btnSaveActionPerformed
     * Purpose: Reads all fields and adds a new Student or PolytechnicStaff
     * member to the GymSystem (Req-3). The memberID is assigned automatically.
     *
     * @param evt the action event
*/
    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
try {
            String firstName = txtFirstName.getText().trim();
            String surname   = txtSurname.getText().trim();
            String phone     = txtPhone.getText().trim();
            String dob       = txtDOB.getText().trim();
            String address   = txtAddress.getText().trim();

            if (firstName.isEmpty() || surname.isEmpty() || phone.isEmpty()
                    || dob.isEmpty() || address.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "* Missing required field",
                        "Validation Error",
                        javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }

            if (!btnMale.isSelected() && !btnFemale.isSelected()) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Please select a Gender.",
                        "Validation Error",
                        javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }

            if (!btnStaff.isSelected() && !btnStudent.isSelected()) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Please select a Member Type.",
                        "Validation Error",
                        javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }

            String gender = btnMale.isSelected() ? "Male" : "Female";

            if (btnStaff.isSelected()) {
                String position   = jTextField6.getText().trim();
                String department = jTextField7.getText().trim();
                if (position.isEmpty() || department.isEmpty()) {
                    javax.swing.JOptionPane.showMessageDialog(this,
                            "Please fill in Position and Department.",
                            "Validation Error",
                            javax.swing.JOptionPane.ERROR_MESSAGE);
                    return;
                }
                PolytechnicStaff ps = gym.addPolytechnicStaff(position, department,
                        dob, gender, firstName, surname, phone, "", address);
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Staff added!\nMember ID: " + ps.getMemberID(),
                        "Success",
                        javax.swing.JOptionPane.INFORMATION_MESSAGE);
            } else {
                String course = jTextField8.getText().trim();
                String team   = jTextField9.getText().trim();
                if (course.isEmpty()) {
                    javax.swing.JOptionPane.showMessageDialog(this,
                            "Please fill in Course.",
                            "Validation Error",
                            javax.swing.JOptionPane.ERROR_MESSAGE);
                    return;
                }
                Students s = gym.addStudent(course, team, dob, gender,
                        firstName, surname, phone, "", address);
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Student added!\nMember ID: " + s.getMemberID(),
                        "Success",
                        javax.swing.JOptionPane.INFORMATION_MESSAGE);
            }

            txtFirstName.setText("");
            txtSurname.setText("");
            txtPhone.setText("");
            txtDOB.setText("");
            txtAddress.setText("");
            btngrpGender.clearSelection();
            btngrpMember.clearSelection();
            jTextField6.setText("");
            jTextField7.setText("");
            jTextField8.setText("");
            jTextField9.setText("");
            pnlStaff.setVisible(false);
            pnlStudent.setVisible(false);

        } catch (InvalidDataException | DuplicateIDException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    e.getMessage(),
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSaveActionPerformed

