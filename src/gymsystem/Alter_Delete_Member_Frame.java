 /**
     * Name: loadMembers
     * Purpose: Loads all members from GymSystem into the table (Req-4, Req-9).
     * Sets up Alter/Delete button renderer and editor. Sets up live search.
     */
    private void loadMembers() {
        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        jTable1.setRowHeight(40);
jTable1.setShowGrid(false);
jTable1.getTableHeader().setBackground(new java.awt.Color(52, 83, 102));
jTable1.getTableHeader().setForeground(java.awt.Color.WHITE);
jTable1.getTableHeader().setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 13));
jTable1.getTableHeader().setPreferredSize(new java.awt.Dimension(0, 38));
jTable1.setSelectionBackground(new java.awt.Color(210, 225, 245));
jTable1.setFont(new java.awt.Font("Segoe UI", java.awt.Font.PLAIN, 13));

        for (Member m : gym.getMembers()) {
            String type = (m instanceof Students) ? "Student" : "Staff";
            model.addRow(new Object[]{
                m.getMemberID(),
                m.getFirstName() + " " + m.getSurname(),
                type,
                ""
            });
        }

        javax.swing.table.TableRowSorter<javax.swing.table.DefaultTableModel> sorter =
                new javax.swing.table.TableRowSorter<>(model);
        jTable1.setRowSorter(sorter);

        searchid.addKeyListener(new java.awt.event.KeyAdapter() {
            public void keyReleased(java.awt.event.KeyEvent evt) {
                String q = searchid.getText();
                sorter.setRowFilter(q.trim().isEmpty() ? null :
                        javax.swing.RowFilter.regexFilter("(?i)" + q, 0, 1, 2));
            }
        });

        jTable1.getColumnModel().getColumn(3).setCellRenderer((t, v, s, f, r, c) -> createActionPanel());

        jTable1.getColumnModel().getColumn(3).setCellEditor(
                new javax.swing.DefaultCellEditor(new javax.swing.JCheckBox()) {
            private final javax.swing.JPanel panel = createActionPanel();
            {
                ((javax.swing.JButton) panel.getComponent(0)).addActionListener(e -> {
                    fireEditingStopped();
                    int row = jTable1.getSelectedRow();
                    if (row < 0) return;
                    int memberID = (int) jTable1.getValueAt(row, 0);
                    Member m = gym.findMemberByID(memberID);
                    if (m == null) return;

                    javax.swing.JTextField f1 = new javax.swing.JTextField(m.getFirstName(), 12);
                    javax.swing.JTextField f2 = new javax.swing.JTextField(m.getSurname(), 12);
                    javax.swing.JTextField f3 = new javax.swing.JTextField(m.getPhone(), 12);
                    javax.swing.JTextField f4 = new javax.swing.JTextField(m.getAddress(), 12);
                    javax.swing.JTextField f5 = new javax.swing.JTextField(m.getDOB(), 12);
                    javax.swing.JComboBox<String> cb = new javax.swing.JComboBox<>(new String[]{"Male", "Female"});
                    cb.setSelectedItem(m.getGender());

                    javax.swing.JPanel p = new javax.swing.JPanel(new java.awt.GridLayout(6, 2, 5, 5));
                    p.add(new javax.swing.JLabel("First Name:")); p.add(f1);
                    p.add(new javax.swing.JLabel("Surname:"));   p.add(f2);
                    p.add(new javax.swing.JLabel("Phone:"));     p.add(f3);
                    p.add(new javax.swing.JLabel("Address:"));   p.add(f4);
                    p.add(new javax.swing.JLabel("DOB:"));       p.add(f5);
                    p.add(new javax.swing.JLabel("Gender:"));    p.add(cb);

                    if (javax.swing.JOptionPane.showConfirmDialog(null, p, "Alter Member",
                            javax.swing.JOptionPane.OK_CANCEL_OPTION) == javax.swing.JOptionPane.OK_OPTION) {
                        try {
                            gym.updateMember(memberID, f1.getText().trim(), f2.getText().trim(),
                                    f3.getText().trim(), m.getEmail(), f4.getText().trim(),
                                    f5.getText().trim(), cb.getSelectedItem().toString());
                            model.setValueAt(f1.getText().trim() + " " + f2.getText().trim(), row, 1);
                        } catch (Exception ex) {
                            javax.swing.JOptionPane.showMessageDialog(null, ex.getMessage());
                        }
                    }
                });

                ((javax.swing.JButton) panel.getComponent(1)).addActionListener(e -> {
                    fireEditingStopped();
                    int row = jTable1.getSelectedRow();
                    if (row < 0) return;
                    int memberID = (int) jTable1.getValueAt(row, 0);
                    if (javax.swing.JOptionPane.showConfirmDialog(null,
                            "Delete this member?", "Confirm",
                            javax.swing.JOptionPane.YES_NO_OPTION) == javax.swing.JOptionPane.YES_OPTION) {
                        gym.deleteMember(memberID);
                        model.removeRow(row);
                    }
                });
            }
            public java.awt.Component getTableCellEditorComponent(
                    javax.swing.JTable t, Object v, boolean s, int r, int c) { return panel; }
        });
    }
 
