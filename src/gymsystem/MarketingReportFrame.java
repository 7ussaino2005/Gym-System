    /**
     * Name: loadReport
     * Purpose: Populates the content panel with Staff and Student sections (Req-11).
     */
    private void loadReport() {
        jScrollPane1.removeAll();
        jScrollPane1.setLayout(new javax.swing.BoxLayout(jScrollPane1, javax.swing.BoxLayout.Y_AXIS));

        jScrollPane1.add(createSectionHeader("Polytechnic STAFF MEMBERS",
                new java.awt.Color(52, 83, 102), java.awt.Color.WHITE));

        int staffCount = 0;
        for (Member m : gym.getMembers()) {
            if (m instanceof PolytechnicStaff) {
                PolytechnicStaff ps = (PolytechnicStaff) m;
                jScrollPane1.add(createMemberCard(
                        ps.getFirstName() + " " + ps.getSurname(),
                        ps.getAddress(), ps.getPhone(),
                        ps.getPosition(), ps.getDepartment()));
                staffCount++;
            }
        }
        jScrollPane1.add(createTotalLabel("Total Staff Members: " + staffCount));
        jScrollPane1.add(javax.swing.Box.createVerticalStrut(8));

        jScrollPane1.add(createSectionHeader("Polytechnic Students",
                new java.awt.Color(0, 153, 51), java.awt.Color.WHITE));

        int studentCount = 0;
        for (Member m : gym.getMembers()) {
            if (m instanceof Students) {
                Students s = (Students) m;
                jScrollPane1.add(createMemberCard(
                        s.getFirstName() + " " + s.getSurname(),
                        s.getAddress(), s.getPhone(),
                        s.getCourse(),
                        s.getTeam().isEmpty() ? "None" : s.getTeam()));
                studentCount++;
            }
        }
        jScrollPane1.add(createTotalLabel("Total Students: " + studentCount));

        jScrollPane1.revalidate();
        jScrollPane1.repaint();
    }
    
      /**
     * Name: createSectionHeader
     * Purpose: Creates a coloured section header panel.
     *
     * @param title      section title text
     * @param background background colour
     * @param foreground text colour
     * @return JPanel header
     */
    private javax.swing.JPanel createSectionHeader(String title,
            java.awt.Color background, java.awt.Color foreground) {
        javax.swing.JPanel p = new javax.swing.JPanel(new java.awt.BorderLayout());
        p.setBackground(background);
        p.setMaximumSize(new java.awt.Dimension(Integer.MAX_VALUE, 40));
        p.setBorder(javax.swing.BorderFactory.createEmptyBorder(8, 12, 8, 12));
        javax.swing.JLabel lbl = new javax.swing.JLabel(title);
        lbl.setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 14));
        lbl.setForeground(foreground);
        p.add(lbl, java.awt.BorderLayout.WEST);
        return p;
    }
    
    /**
     * Name: createMemberCard
     * Purpose: Creates a card panel displaying one member's details.
     *
     * @param name    full name
     * @param address address
     * @param phone   phone number
     * @param line1   first extra info line
     * @param line2   second extra info line
     * @return JPanel card
     */
    private javax.swing.JPanel createMemberCard(String name, String address,
            String phone, String line1, String line2) {
        javax.swing.JPanel card = new javax.swing.JPanel();
        card.setLayout(new java.awt.GridLayout(0, 1, 0, 2));
        card.setBackground(java.awt.Color.WHITE);
        card.setBorder(javax.swing.BorderFactory.createCompoundBorder(
                javax.swing.BorderFactory.createMatteBorder(0, 0, 1, 0,
                        new java.awt.Color(220, 220, 220)),
                javax.swing.BorderFactory.createEmptyBorder(8, 12, 8, 12)));
        card.setMaximumSize(new java.awt.Dimension(Integer.MAX_VALUE, 80));

        javax.swing.JLabel lblName = new javax.swing.JLabel(name);
        lblName.setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 13));

        javax.swing.JLabel lblAddr = new javax.swing.JLabel(address + "  |  " + phone);
        lblAddr.setFont(new java.awt.Font("Segoe UI", java.awt.Font.PLAIN, 12));
        lblAddr.setForeground(new java.awt.Color(80, 80, 80));

        javax.swing.JLabel lblExtra = new javax.swing.JLabel(line1 + "  |  " + line2);
        lblExtra.setFont(new java.awt.Font("Segoe UI", java.awt.Font.PLAIN, 12));
        lblExtra.setForeground(new java.awt.Color(80, 80, 80));

        card.add(lblName);
        card.add(lblAddr);
        card.add(lblExtra);
        return card;
    }

    /**
     * Name: createTotalLabel
     * Purpose: Creates a styled total count label.
     *
     * @param text the total text to display
     * @return JPanel containing the label
     */
    private javax.swing.JPanel createTotalLabel(String text) {
        javax.swing.JPanel p = new javax.swing.JPanel(
                new java.awt.FlowLayout(java.awt.FlowLayout.LEFT, 12, 6));
        p.setBackground(java.awt.Color.WHITE);
        p.setMaximumSize(new java.awt.Dimension(Integer.MAX_VALUE, 35));
        javax.swing.JLabel lbl = new javax.swing.JLabel(text);
        lbl.setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 12));
        lbl.setForeground(new java.awt.Color(24, 95, 165));
        p.add(lbl);
        return p;
    }

    
    
