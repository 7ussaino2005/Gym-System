    /**
     * Name: loadMembers
     * Purpose: Loads all members into the table with a JComboBox
     * in the Assign Trainer column (Req-6, Req-7).
     */
    private void loadMembers() {
        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        jTable1.setRowHeight(40);
    jTable1.setShowGrid(false);
    jTable1.getTableHeader().setBackground(new java.awt.Color(52, 83, 102));
    jTable1.getTableHeader().setForeground(java.awt.Color.WHITE);
    jTable1.getTableHeader().setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 13));
    jTable1.getTableHeader().setPreferredSize(new java.awt.Dimension(0, 38));
    jTable1.setSelectionBackground(new java.awt.Color(210, 225, 245));
    jTable1.setFont(new java.awt.Font("Segoe UI", java.awt.Font.PLAIN, 13));
        ArrayList<PersonalTrainer> trainers = gym.getAllPersonalTrainers();
        String[] trainerOptions = new String[trainers.size() + 1];
        trainerOptions[0] = "-- None --";
        for (int i = 0; i < trainers.size(); i++) {
            trainerOptions[i + 1] = trainers.get(i).getFirstName()
                    + " " + trainers.get(i).getSurname()
                    + " (ID:" + trainers.get(i).getPersonalTrainerID() + ")";
        }

        for (Member m : gym.getMembers()) {
            String type = (m instanceof Students) ? "Student" : "Staff";
            String currentTrainer = "-- None --";
            if (m.getPersonalTrainer() != null) {
                PersonalTrainer pt = m.getPersonalTrainer();
                currentTrainer = pt.getFirstName() + " " + pt.getSurname()
                        + " (ID:" + pt.getPersonalTrainerID() + ")";
            }
            model.addRow(new Object[]{
                m.getMemberID(),
                m.getFirstName() + " " + m.getSurname(),
                type,
                currentTrainer
            });
        }

        javax.swing.JComboBox<String> combo = new javax.swing.JComboBox<>(trainerOptions);
        jTable1.getColumnModel().getColumn(3).setCellEditor(
                new javax.swing.DefaultCellEditor(combo));

        javax.swing.table.TableRowSorter<javax.swing.table.DefaultTableModel> sorter =
                new javax.swing.table.TableRowSorter<>(model);
        jTable1.setRowSorter(sorter);

        jTextField1.addKeyListener(new java.awt.event.KeyAdapter() {
            public void keyReleased(java.awt.event.KeyEvent evt) {
                String q = jTextField1.getText();
                sorter.setRowFilter(q.trim().isEmpty() ? null :
                        javax.swing.RowFilter.regexFilter("(?i)" + q, 0, 1));
            }
        });
    }
    
    /**
     * Name: btnSaveActionPerformed
     * Purpose: Saves trainer assignments for all members (Req-6, Req-7).
     *
     * @param evt the action event
     */
    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {
        if (jTable1.isEditing()) {
            jTable1.getCellEditor().stopCellEditing();
        }

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel) jTable1.getModel();

        for (int i = 0; i < model.getRowCount(); i++) {
            int memberID = (int) model.getValueAt(i, 0);
            String selected = (String) model.getValueAt(i, 3);

            if (selected == null || selected.equals("-- None --")) {
                Member m = gym.findMemberByID(memberID);
                if (m != null && m.getPersonalTrainer() != null) {
                    int trainerID = m.getPersonalTrainer().getPersonalTrainerID();
                    try {
                        gym.removeMemberFromTrainer(memberID, trainerID);
                    } catch (Exception e) { }
                }
            } else {
                try {
                    int start = selected.lastIndexOf("(ID:") + 4;
                    int end = selected.lastIndexOf(")");
                    int trainerID = Integer.parseInt(selected.substring(start, end));
                    gym.assignMemberToTrainer(memberID, trainerID);
                } catch (Exception e) { }
            }
        }

        javax.swing.JOptionPane.showMessageDialog(this,
                "Trainer assignments saved successfully!",
                "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        dispose();
    }
    
    private void styleTable(javax.swing.JTable table) {
    table.setDefaultRenderer(Object.class, new javax.swing.table.DefaultTableCellRenderer() {
        @Override
        public java.awt.Component getTableCellRendererComponent(
                javax.swing.JTable t, Object v, boolean sel, boolean foc, int r, int c) {
            super.getTableCellRendererComponent(t, v, sel, foc, r, c);
            if (!sel) {
                setBackground(r % 2 == 0 ? java.awt.Color.WHITE : new java.awt.Color(245, 247, 250));
            }
            setBorder(javax.swing.BorderFactory.createEmptyBorder(0, 8, 0, 8));
            return this;
        }
    });
}

