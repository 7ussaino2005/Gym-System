   /**
     * Name: loadTrainers
     * Purpose: Loads all personal trainers from GymSystem into the table (Req-10).
     * Sets up View button renderer and editor. Sets up live search.
     */
    private void loadTrainers() {
        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);

        for (PersonalTrainer pt : gym.getAllPersonalTrainers()) {
            model.addRow(new Object[]{
                pt.getPersonalTrainerID(),
                pt.getFirstName() + " " + pt.getSurname(),
                pt.getMemberCount(),
                ""
            });
        }
            javax.swing.table.TableRowSorter<javax.swing.table.DefaultTableModel> sorter =
                new javax.swing.table.TableRowSorter<>(model);
        jTable1.setRowSorter(sorter);
        jTable1.setRowHeight(40);
        jTextField1.addKeyListener(new java.awt.event.KeyAdapter() {
            public void keyReleased(java.awt.event.KeyEvent evt) {
                String q = jTextField1.getText();
                sorter.setRowFilter(q.trim().isEmpty() ? null :
                        javax.swing.RowFilter.regexFilter("(?i)" + q, 0, 1));
            }
        });

        jTable1.getColumnModel().getColumn(3).setCellRenderer((t, v, s, f, r, c) -> createViewPanel());

        jTable1.getColumnModel().getColumn(3).setCellEditor(
                new javax.swing.DefaultCellEditor(new javax.swing.JCheckBox()) {
            private final javax.swing.JPanel panel = createViewPanel();
            {
                ((javax.swing.JButton) panel.getComponent(0)).addActionListener(e -> {
                    fireEditingStopped();
                    int row = jTable1.getSelectedRow();
                    if (row < 0) return;
                    int trainerID = (int) jTable1.getValueAt(row, 0);
                    showMembersOfTrainer(trainerID);
                });
            }
            public java.awt.Component getTableCellEditorComponent(
                    javax.swing.JTable t, Object v, boolean s, int r, int c) { return panel; }
        });
    }
    
    /**
     * Name: showMembersOfTrainer
     * Purpose: Shows a JTextArea with JScrollPane listing all members
     * assigned to the selected trainer (Req-10).
     *
     * @param trainerID the ID of the selected personal trainer
     */
    private void showMembersOfTrainer(int trainerID) {
        java.util.ArrayList<Member> members = gym.getMembersOfTrainer(trainerID);
        PersonalTrainer pt = gym.findTrainerByTrainerID(trainerID);
        StringBuilder sb = new StringBuilder();
        sb.append("Trainer: ").append(pt.getFirstName()).append(" ").append(pt.getSurname()).append("\n");
        sb.append("─────────────────────────────\n");
        if (members.isEmpty()) {
            sb.append("No members assigned.");
        } else {
            for (Member m : members) {
                sb.append("ID: ").append(m.getMemberID())
                  .append(" | Name: ").append(m.getFirstName()).append(" ").append(m.getSurname())
                  .append(" | Type: ").append(m instanceof Students ? "Student" : "Staff")
                  .append("\n");
            }
        }
        sb.append("─────────────────────────────\n");
        sb.append("Total: ").append(members.size()).append(" member(s)");

        javax.swing.JTextArea txtArea = new javax.swing.JTextArea(sb.toString());
        txtArea.setEditable(false);
        txtArea.setFont(new java.awt.Font("Monospaced", java.awt.Font.PLAIN, 13));
        javax.swing.JScrollPane scroll = new javax.swing.JScrollPane(txtArea);
        scroll.setPreferredSize(new java.awt.Dimension(450, 300));
        javax.swing.JOptionPane.showMessageDialog(this, scroll,
                "Members of Trainer", javax.swing.JOptionPane.INFORMATION_MESSAGE);
    }

