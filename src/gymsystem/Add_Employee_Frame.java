/**
     * Name: btnSaveActionPerformed
     * Purpose: Reads all fields and adds a new Employee or PersonalTrainer
     * to the GymSystem (Req-2). The employeeID is assigned automatically.
     * Shows success or error message to the user.
     *
     * @param evt the action event
     */
    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
 try {
            String firstName = txtFirstName.getText().trim();
            String surname   = txtSurname.getText().trim();
            String phone     = txtPhone.getText().trim();
            String address   = txtAddress.getText().trim();
            String salaryStr = txtDOB.getText().trim();

            if (firstName.isEmpty() || surname.isEmpty() || phone.isEmpty()
                    || address.isEmpty() || salaryStr.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "* Missing required field",
                        "Validation Error",
                        javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }

            if (!btnStaff.isSelected() && !btnStudent.isSelected()) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Please select Employee Type.",
                        "Validation Error",
                        javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }

            double salary     = Double.parseDouble(salaryStr);
            boolean isTrainer = btnStudent.isSelected();

            Employee emp = gym.addEmployee(isTrainer, salary,
                    firstName, surname, phone, "", address);

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Employee added successfully!\nEmployee ID: " + emp.getEmployeeID(),
                    "Success",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE);

            txtFirstName.setText("");
            txtSurname.setText("");
            txtPhone.setText("");
            txtDOB.setText("");
            txtAddress.setText("");
            btngrpType.clearSelection();

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Salary must be a valid number.",
                    "Invalid Salary",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        } catch (InvalidDataException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Invalid data: " + e.getMessage(),
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    
    }//GEN-LAST:event_btnSaveActionPerformed

